#!/usr/bin/env python3
"""Generates src/glsl.aki from the GLSL raw strings in ugui/rhi/opengl/opengl_rhi.cc.

  python3 tools/gen_glsl.py ../../ugui/rhi/opengl/opengl_rhi.cc > src/glsl.aki
"""
import re
import sys

src = open(sys.argv[1]).read()
pat = re.compile(r'static const char\* const (k\w+Src) = R"glsl\((.*?)\)glsl";', re.S)
out = []
w = out.append
w("// ugui/rhi/opengl/opengl_rhi.cc: the embedded GLSL 3.30 core shaders (ported from")
w("// the Vulkan GLSL). Generated by tools/gen_glsl.py; the text is the C++ raw strings.")
w("// ugui_impl_opengl3.cc carries its own copies of the quad and text shaders, which")
w("// differ from these only in layout and comments; both backends use this one.")
w("")
w("module ultragui_opengl::glsl;")
w("")
for m in pat.finditer(src):
    name = m.group(1)
    body = m.group(2).lstrip("\n")
    assert '"""' not in body
    w("pub static let %s: str = r\"\"\"" % name)
    w(body.rstrip("\n"))
    w('"""; ')
    w("")
sys.stdout.write("\n".join(out))
