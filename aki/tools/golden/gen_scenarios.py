#!/usr/bin/env python3
"""Write the golden scenarios in scenarios/ from the example UIs.

Each scenario loads one .ugui (and its Lua, in the _lua variant), settles a few
frames, then plays a seeded walk of input: pointer moves and clicks across the
viewport, drags, wheel scrolls, Tab and arrow focus moves, Enter, and typed
text, rendering a frame after each step with a fixed dt. A seed makes the walk
the same on every run, so the files are checked in and regenerated only when
this script changes.
"""
import pathlib
import random

here = pathlib.Path(__file__).resolve().parent
root = here.parent.parent.parent
FONT = "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf"

UIS = sorted(
    [p for p in (root / "examples").rglob("*.ugui")],
    key=lambda p: str(p))

# GLFW key codes, as ultragui uses them.
TAB, ENTER, BACKSPACE, RIGHT, LEFT, DOWN, UP, ESCAPE = 258, 257, 259, 262, 263, 264, 265, 256


def walk(rng, w, h, steps):
    out = []
    for _ in range(steps):
        r = rng.random()
        x, y = rng.uniform(0, w), rng.uniform(0, h)
        if r < 0.45:
            out += [f"move {x:.1f} {y:.1f}", "frame"]
        elif r < 0.70:
            out += [f"move {x:.1f} {y:.1f}", "frame", "down left", "frame",
                    "up left", "frame"]
        elif r < 0.78:
            x2, y2 = x + rng.uniform(-80, 80), y + rng.uniform(-80, 80)
            out += [f"move {x:.1f} {y:.1f}", "down left", "frame",
                    f"move {x2:.1f} {y2:.1f}", "frame", "up left", "frame"]
        elif r < 0.85:
            out += [f"move {x:.1f} {y:.1f}",
                    f"scroll 0 {rng.choice([-3, -1, 1, 3])}", "frame"]
        elif r < 0.93:
            k = rng.choice([TAB, TAB, RIGHT, LEFT, DOWN, UP, ENTER, ESCAPE])
            mods = 1 if (k == TAB and rng.random() < 0.3) else 0
            out += [f"key {k} 0 1 0 {mods}", f"key {k} 0 0 0 {mods}", "frame"]
        else:
            for ch in rng.choice(["hello", "ultra", "aki 42", "é ✓"]):
                out.append(f"char {ord(ch)}")
            out += [f"key {BACKSPACE} 0 1 0 0", f"key {BACKSPACE} 0 0 0 0",
                    "frame"]
        if rng.random() < 0.15:
            out.append(f"frames {rng.randint(2, 20)} 0.016666")
    return out


def scenario(ui, lua, seed):
    rng = random.Random(seed)
    w, h = 1280, 720
    rel = ui.relative_to(root)
    lines = [f"# generated by gen_scenarios.py from {rel}, seed {seed}",
             f"viewport {w} {h} {w} {h}", f"font {FONT}", f"ui {rel}"]
    if lua:
        lines.append(f"script {lua.relative_to(root)}")
    lines += ["frames 3 0.016666"]
    lines += walk(rng, w, h, 120)
    # A resize, then a high-DPI framebuffer, then a scaled UI.
    lines += ["viewport 960 540 960 540", "frames 2 0.016666",
              "viewport 1280 720 2560 1440", "frames 2 0.016666",
              "ui_scale 1.5", "frames 2 0.016666", "ui_scale 0", "frame"]
    lines += walk(rng, w, h, 30)
    lines += ["frames 120 0.016666"]
    return "\n".join(lines) + "\n"


def main():
    out = here / "scenarios"
    out.mkdir(exist_ok=True)
    for old in out.glob("*.txt"):
        old.unlink()
    for i, ui in enumerate(UIS):
        name = "_".join(ui.relative_to(root / "examples").with_suffix("").parts)
        (out / f"{name}.txt").write_text(scenario(ui, None, 1000 + i))
        lua = ui.with_suffix(".lua")
        if not lua.exists() and ui.name == "ui.ugui":
            lua = ui.parent / "logic.lua"
        if lua.exists():
            (out / f"{name}_lua.txt").write_text(scenario(ui, lua, 2000 + i))
    print("\n".join(sorted(p.name for p in out.glob("*.txt"))))


if __name__ == "__main__":
    main()
