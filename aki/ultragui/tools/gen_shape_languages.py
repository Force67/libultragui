#!/usr/bin/env python3
"""Generate language_tables.aki from HarfBuzz 13.2.1 src/hb-ot-tag-table.hh.

Usage: python3 tools/gen_shape_languages.py HARFBUZZ_SOURCE
Run from any directory. No HarfBuzz library is linked into the engine.
The ordered complex rules are data (exact, language-prefix, prefix/subtag,
variant); assertions reject source constructs this extractor cannot read.
"""
import re
import sys
from pathlib import Path

TAG = r"HB_TAG\('(.?)','(.?)','(.?)','(.?)'\)"

def tags(text):
    return [int.from_bytes(''.join(t).encode('ascii'), 'big') for t in re.findall(TAG, text)]

def main():
    source = Path(sys.argv[1]) / 'src/hb-ot-tag-table.hh'
    text = source.read_text()
    def array(name):
        return re.search(r'\b' + name + r'\[\] = \{(.*?)\n\};', text, re.S)[1]
    mappings = {}
    for name in ['ot_languages2', 'ot_languages3']:
        for row in array(name).splitlines():
            ts = tags(row.split('/*')[0])
            if ts:
                assert len(ts) == 2, row
                mappings.setdefault(ts[0], []).append(ts[1])
    values = tags(re.sub(r'/\*.*?\*/', '', array('ot_languages3_multi_values'), flags=re.S))
    for row in array('ot_languages3_multi').splitlines():
        ts = tags(row.split('/*')[0])
        if ts:
            offset, count = map(int, re.search(r'\),\s*(\d+),\s*(\d+)', row).groups())
            assert ts[0] not in mappings
            mappings[ts[0]] = values[offset:offset+count]
    for t in tags(re.sub(r'/\*.*?\*/', '', array('ot_languages3_blocked'), flags=re.S)):
        assert t not in mappings
        mappings[t] = []
    complex_text = text.split('hb_ot_tags_from_complex_language (')[1].split('out:')[0]
    rules = []
    for cond, body in re.findall(r'if \((subtag_matches .*?)\)\s*\{(.*?)return true;\s*\}', complex_text, re.S):
        variant = re.search(r'"([^"]+)"', cond)[1]
        rules.append((3, '', variant, tags(body)))
    assert len(rules) == 9
    cases = text.split('out:')[1].split('  return false;')[0]
    for initial, body in re.findall(r"case '(.)':(.*?)\n    break;", cases, re.S):
        for cond, result in re.findall(r'if \((.*?)\)\s*\{(.*?)return true;\s*\}', body, re.S):
            cond = ' '.join(cond.split())
            words = re.findall(r'"([^"]+)"', cond)
            if cond.startswith('lang_matches '):
                mode = 1
                assert len(words) == 1
            elif cond.startswith('0 == strcmp '):
                mode = 0
                assert len(words) == 1
            else:
                mode = 2
                assert cond.startswith('0 == strncmp ') and '&& subtag_matches ' in cond and len(words) == 2, cond
            rules.append((mode, initial + words[0], words[1] if mode == 2 else '', tags(result)))
    assert len(rules) == 148, len(rules)
    out = ['// Generated by tools/gen_shape_languages.py from HarfBuzz 13.2.1.',
           '// Language registry data and ordered disambiguation rules; do not edit.',
           '// HarfBuzz copyright and permission notice: data/HARFBUZZ-LICENSE.',
           'module ultragui::shape::language_tables;', '',
           '// Sorted rows: ISO tag, count, up to three ordered OT tags (zero padded).',
           f'pub static let kLanguages: [u32; {len(mappings)*5}] = [']
    for key, ts in sorted(mappings.items()):
        assert len(ts) <= 3
        out.append('  ' + ', '.join(f'0x{x:08X}' for x in [key, len(ts)] + ts + [0]*(3-len(ts))) + ',')
    out += ['];', '', 'pub struct LanguageRule : Copy {',
            '  pub let mode: u32', '  pub let prefix: str', '  pub let subtag: str',
            '  pub let tags: [u32; 3]', '  pub let count: usize', '}', '',
            f'pub static let kLanguageRules: [LanguageRule; {len(rules)}] = [']
    for mode, prefix, subtag, ts in rules:
        assert 0 < len(ts) <= 3
        out.append(f'  LanguageRule {{ mode: {mode}, prefix: "{prefix}", subtag: "{subtag}", tags: [' +
                   ', '.join(f'0x{x:08X}' for x in ts + [0]*(3-len(ts))) + f'], count: {len(ts)} }},')
    out += ['];', '']
    dest = Path(__file__).resolve().parent.parent / 'src/shape/language_tables.aki'
    dest.write_text('\n'.join(out))
    print(f'{len(mappings)} mappings, {len(rules)} complex rules -> {dest}')

if __name__ == '__main__':
    main()
