#!/usr/bin/env python3
"""Turns the output of gen_svg_reference (stdin) into tests/support/svg_corpus.aki.

    /tmp/gen_svg_reference aki/ultragui/tests/data/svg | python3 aki/ultragui/tools/gen_svg_table.py > aki/ultragui/tests/support/svg_corpus.aki
"""
import sys

rows = [l.split() for l in sys.stdin if l.startswith("SVG ")]
names = []
for r in rows:
    if r[1] not in names:
        names.append(r[1])

print("""// Generated by tools/gen_svg_table.py from tools/gen_svg_reference.cc: the
// corpus files (tests/data/svg/) and the FNV-1a hash of the RGBA8 pixels the
// C++ rasterizes for each render. Do not edit.

module support::svg_corpus;

pub struct SvgFile {
  pub let name: str
  pub let data: bytes
}

pub struct SvgCase {
  pub let file: str
  pub let width: u32   // requested size, 0 for the SVG's own
  pub let height: u32
  pub let ok: bool
  pub let hash: u64
}
""")
print(f"pub static let kFiles: [SvgFile; {len(names)}] = [")
for n in names:
    print(f'  SvgFile {{ name: "{n}", data: @embed("../data/svg/{n}.svg") }},')
print("];\n")
print(f"pub static let kCases: [SvgCase; {len(rows)}] = [")
for _, f, w, h, ok, hs in rows:
    print(f'  SvgCase {{ file: "{f}", width: {w}, height: {h}, ok: {"true" if ok == "1" else "false"}, hash: {hs} }},')
print("];")
