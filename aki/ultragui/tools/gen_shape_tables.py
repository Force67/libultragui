#!/usr/bin/env python3
"""Packs the dump of tools/gen_shape_tables.cc into the shaper's tables.

  python3 tools/gen_shape_tables.py DUMP_DIR

writes src/shape/data/ucd.bin (the per-code-point properties, two-level
compressed, and the sorted mirroring, decomposition, composition and Arabic
PUA lists) and src/shape/ucd_tables.aki (where each part of ucd.bin starts,
the script list and the small tables). Run from aki/ultragui.
"""

import os
import struct
import sys

BLOCK = 128


def main():
    dump = sys.argv[1]
    here = os.path.dirname(os.path.abspath(__file__))
    out_dir = os.path.join(here, "..", "src", "shape")
    data = open(os.path.join(dump, "ucd.bin"), "rb").read()
    n = 0x110000
    rec_size = 24
    assert len(data) == n * rec_size

    scripts = []
    for line in open(os.path.join(dump, "scripts.txt")):
        f = [int(x) for x in line.split()]
        tag, direction, sn = f[0], f[1], f[2]
        stags = f[3:3 + sn]
        ln = f[3 + sn]
        assert ln == 0, "language 'c' maps to no OpenType language tag"
        shaper = f[4 + sn]
        assert shaper < 10
        scripts.append((tag, direction, stags, shaper))
    script_index = {s[0]: i for i, s in enumerate(scripts)}
    assert len(scripts) < 256

    records = {}
    record_list = []
    rids = []
    mirrors = []
    decomps = []
    for u in range(n):
        gc, ccc, jt, use, indic, flags, _pad, mirror, script, da, db = struct.unpack_from(
            "<BBBBHBBIIII", data, u * rec_size)
        rec = (gc, ccc, script_index[script], flags, jt, use, indic & 0xFF, indic >> 8)
        rid = records.get(rec)
        if rid is None:
            rid = len(record_list)
            records[rec] = rid
            record_list.append(rec)
        rids.append(rid)
        if mirror != u:
            mirrors.append((u, mirror))
        if da:
            decomps.append((u, da, db))
    assert len(record_list) < 65536

    blocks = {}
    block_list = []
    index = []
    for b in range(n // BLOCK):
        chunk = tuple(rids[b * BLOCK:(b + 1) * BLOCK])
        bid = blocks.get(chunk)
        if bid is None:
            bid = len(block_list)
            blocks[chunk] = bid
            block_list.append(chunk)
        index.append(bid)

    composes = []
    for line in open(os.path.join(dump, "compose.txt")):
        a, b, ab = (int(x) for x in line.split())
        composes.append((a, b, ab))
    composes.sort()

    puas = []
    for line in open(os.path.join(dump, "pua.txt")):
        u, s, t = (int(x) for x in line.split())
        puas.append((u, s, t))

    out = bytearray()
    offsets = {}
    offsets["index"] = len(out)
    for bid in index:
        out += struct.pack("<H", bid)
    offsets["blocks"] = len(out)
    for chunk in block_list:
        for rid in chunk:
            out += struct.pack("<H", rid)
    offsets["records"] = len(out)
    for rec in record_list:
        out += bytes(rec)
    offsets["mirrors"] = len(out)
    for u, m in mirrors:
        out += struct.pack("<II", u, m)
    offsets["decomps"] = len(out)
    for u, a, b in decomps:
        out += struct.pack("<III", u, a, b)
    offsets["composes"] = len(out)
    for a, b, ab in composes:
        out += struct.pack("<III", a, b, ab)
    offsets["puas"] = len(out)
    for u, s, t in puas:
        out += struct.pack("<HHH", u, s, t)
    os.makedirs(os.path.join(out_dir, "data"), exist_ok=True)
    open(os.path.join(out_dir, "data", "ucd.bin"), "wb").write(out)

    mcc = [int(x) for x in open(os.path.join(dump, "mcc.txt")).read().split()]
    assert len(mcc) == 256

    shaping = []
    lig2 = []
    ligmark = []
    lig3 = []
    first_last = None
    for line in open(os.path.join(dump, "arabic.txt")):
        f = line.split()
        if f[0] == "shaping":
            first_last = (int(f[1]), int(f[2]))
        elif f[0] == "lig2":
            lig2.append(tuple(int(x) for x in f[1:]))
        elif f[0] == "ligmark":
            ligmark.append(tuple(int(x) for x in f[1:]))
        elif f[0] == "lig3":
            lig3.append(tuple(int(x) for x in f[1:]))
        else:
            shaping.append(tuple(int(x) for x in f))

    def arr(name, typ, values, per_line=12):
        lines = []
        for i in range(0, len(values), per_line):
            lines.append("  " + ", ".join(str(v) for v in values[i:i + per_line]) + ",")
        return f"pub static let {name}: [{typ}; {len(values)}] = [\n" + "\n".join(lines) + "\n];\n"

    w = []
    w.append("// Generated by tools/gen_shape_tables.py from HarfBuzz 13.2.1's own tables\n"
             "// (tools/gen_shape_tables.cc). Do not edit.\n"
             "//\n"
             "// data/ucd.bin holds, little endian: a u16 block number per 128 code points,\n"
             "// the blocks (a u16 record number per code point), the 8-byte records\n"
             "// (general category, combining class, script index, flags (1 default\n"
             "// ignorable, 2 Extended_Pictographic), Arabic joining type, USE category,\n"
             "// Indic category, Indic position), then sorted lists: mirroring pairs\n"
             "// (u32 u, u32 mirror), decompositions (u32 u, a, b; Hangul is algorithmic),\n"
             "// compositions (u32 a, b, ab, sorted by a then b) and the Arabic PUA maps of\n"
             "// symbol fonts (u16 u, simplified, traditional).\n\n"
             "module ultragui::shape::ucd_tables;\n\n")
    w.append("pub static let kUcdData: bytes = @embed(\"data/ucd.bin\");\n\n")
    w.append(f"pub comptime let kUcdBlockShift: u32 = {BLOCK.bit_length() - 1};\n")
    for k in ["index", "blocks", "records", "mirrors", "decomps", "composes", "puas"]:
        w.append(f"pub comptime let kUcd{k.capitalize()}: usize = {offsets[k]};\n")
    w.append(f"pub comptime let kUcdMirrorCount: usize = {len(mirrors)};\n")
    w.append(f"pub comptime let kUcdDecompCount: usize = {len(decomps)};\n")
    w.append(f"pub comptime let kUcdComposeCount: usize = {len(composes)};\n")
    w.append(f"pub comptime let kUcdPuaCount: usize = {len(puas)};\n\n")
    w.append("// Scripts (hb_script_t tags) in the order the records number them, with\n"
             "// hb_script_get_horizontal_direction (4 LTR, 5 RTL, 0 invalid) and the\n"
             "// OpenType script tags hb_ot_tags_from_script_and_language gives for the\n"
             "// language \"c\" (which gives no language tag).\n")
    w.append(arr("kScriptTags", "u32", [s[0] for s in scripts], 8))
    w.append(arr("kScriptDirections", "u8", [s[1] for s in scripts], 32))
    w.append(arr("kScriptOtTagCounts", "u8", [len(s[2]) for s in scripts], 32))
    ot = []
    for s in scripts:
        t = list(s[2]) + [0] * (3 - len(s[2]))
        ot += t
    w.append(arr("kScriptOtTags", "u32", ot, 6))
    w.append("// hb_ot_shaper_categorize for a GSUB script tag of the script's own: 0 default,\n"
             "// 1 Arabic, 2 Thai, 3 Hangul, 4 Hebrew, 5 Indic, 6 Khmer, 7 Myanmar, 8 USE,\n"
             "// 9 Myanmar Zawgyi.\n")
    w.append(arr("kScriptShapers", "u8", [s[3] for s in scripts], 32))
    w.append("\n// _hb_modified_combining_class\n")
    w.append(arr("kModifiedCombiningClass", "u8", mcc, 16))
    w.append(f"\n// The Arabic fallback shaping table: isolated, final, initial, medial\n"
             f"// presentation forms (hb-ot-shaper-arabic-table.hh's order: initial,\n"
             f"// medial, final, isolated) for U+{first_last[0]:04X}..U+{first_last[1]:04X}.\n")
    w.append(f"pub comptime let kArabicShapingFirst: u32 = {first_last[0]};\n")
    w.append(f"pub comptime let kArabicShapingLast: u32 = {first_last[1]};\n")
    flat = []
    for r in shaping:
        flat += list(r)
    w.append(arr("kArabicShaping", "u16", flat, 8))
    w.append("// Ligatures: first, second, ligature (in table order).\n")
    w.append(arr("kArabicLigatures", "u16", [x for t in lig2 for x in t], 9))
    w.append(arr("kArabicMarkLigatures", "u16", [x for t in ligmark for x in t], 9))
    w.append("// Three-component ligatures: first, second, third, ligature.\n")
    w.append(arr("kArabicLigatures3", "u16", [x for t in lig3 for x in t], 8))
    open(os.path.join(out_dir, "ucd_tables.aki"), "w").write("".join(w))
    print(f"{len(record_list)} records, {len(block_list)} blocks, {len(out)} bytes; "
          f"{len(mirrors)} mirrors, {len(decomps)} decompositions, {len(composes)} compositions")


main()
